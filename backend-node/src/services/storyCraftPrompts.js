const SHORT_DRAMA_CRAFT_EN = `【SHORT-DRAMA CRAFT】
- **Golden 3 seconds**: the first image of every episode must present conflict, mystery or an information gap. Never open with weather, scenery or character introduction.
- **One reversal per episode**: something the audience believed gets overturned.
- **One emotional peak per episode**: an outburst, an exposure, a rupture, or a rescue.
- **Cliffhanger ending**: stop mid-action or one second before a truth lands. Never resolve.
- **Short lines**: keep each spoken line under ~15 words. Dialogue drives conflict; it never explains backstory.
- **Information asymmetry**: at every moment one party knows something another does not. That is where suspense comes from.`;

function editablePrompt(key, fallback, episodeCount) {
  try {
    const custom = require('./promptI18n').getOverrideInMemory(key);
    if (custom) return String(custom).replace(/\$\{n\}/g, String(episodeCount || 1));
  } catch (_) {}
  return fallback;
}

