/**
 * 剧本三段式提示词：故事圣经 → 分集节拍表 → 逐集正文。
 *
 * 旧流程是「一次调用吐出 N 集 × 800 字的 JSON 数组」，长输出必然质量塌陷，
 * 且没有任何跨集的设定约束，角色/世界观会逐集漂移。
 *
 * 三段式的关键收益：
 *   1. 每次调用只做一件事，输出长度可控；
 *   2. 故事圣经作为跨集不变量，杜绝设定漂移；
 *   3. 第三段返回纯文本正文，不再受 JSON 转义/截断影响。
 */

